/**
 * 개인정보 가리기 (2차 방어선).
 * 앱에서 이미 가리지만, 구버전 앱이나 앱 쪽 누락에 대비해 서버에서도 한 번 더 가린다.
 * 감정 분석에는 번호 자체가 필요 없으므로 [전화번호] 같은 자리표시로 바꿔도 판단이 달라지지 않는다.
 *
 * 순서가 중요하다: 더 구체적인 형식(주민번호, 카드)을 먼저 바꿔야
 * 일반 숫자열 규칙(계좌)이 먼저 먹어버리지 않는다.
 */

const RULES: ReadonlyArray<readonly [RegExp, string]> = [
  // 이메일
  [/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, "[이메일]"],
  // 주민등록번호·외국인등록번호: 6자리-7자리 (뒷자리 첫 숫자 1~8)
  [/(?<!\d)\d{6}\s?-\s?[1-8]\d{6}(?!\d)/g, "[주민번호]"],
  // 카드번호: 4-4-4-4 (구분자 공백/하이픈/없음)
  [/(?<!\d)\d{4}[\s-]?\d{4}[\s-]?\d{4}[\s-]?\d{4}(?!\d)/g, "[카드번호]"],
  // 휴대폰: 010-1234-5678, 01012345678, +82 10 1234 5678
  [/(?:\+82[\s-]?|(?<!\d)0)1[016789][\s-]?\d{3,4}[\s-]?\d{4}(?!\d)/g, "[전화번호]"],
  // 일반 전화: 02-123-4567, 031-1234-5678
  [/(?<!\d)0\d{1,2}-\d{3,4}-\d{4}(?!\d)/g, "[전화번호]"],
  // 계좌번호: 하이픈이 섞인 10~16자리 숫자 묶음, 또는 하이픈 없는 11~16자리
  [/(?<!\d)\d{2,6}-\d{2,6}-\d{2,8}(?:-\d{1,4})?(?!\d)/g, "[계좌번호]"],
  [/(?<!\d)\d{11,16}(?!\d)/g, "[계좌번호]"],
];

export function maskPii(text: string): string {
  let out = text;
  for (const [pattern, label] of RULES) out = out.replace(pattern, label);
  return out;
}
