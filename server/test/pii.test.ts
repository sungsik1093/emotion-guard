import { describe, expect, it } from "vitest";
import { maskPii } from "../src/pii";

describe("maskPii", () => {
  it.each([
    ["내 번호 010-1234-5678로 연락해", "내 번호 [전화번호]로 연락해"],
    ["01012345678", "[전화번호]"],
    ["+82 10 1234 5678 이야", "[전화번호] 이야"],
    ["회사 02-123-4567", "회사 [전화번호]"],
    ["메일은 me.test@example.co.kr", "메일은 [이메일]"],
    ["주민번호 990101-1234567", "주민번호 [주민번호]"],
    ["카드 1234 5678 9012 3456", "카드 [카드번호]"],
    ["계좌 110-123-456789 로 보내", "계좌 [계좌번호] 로 보내"],
    ["국민 123456789012", "국민 [계좌번호]"],
  ])("%s", (input, expected) => {
    expect(maskPii(input)).toBe(expected);
  });

  it("평범한 숫자와 날짜는 건드리지 않는다", () => {
    for (const text of ["3시에 보자", "2026년 11월 17일", "1000원만", "ㅋㅋㅋ 100점"]) {
      expect(maskPii(text)).toBe(text);
    }
  });
});
